import { chromium } from 'playwright-core';
import { resolve } from 'node:path';
import { mkdirSync } from 'node:fs';
mkdirSync('.shots-save', { recursive: true });
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 }, locale: 'sv-SE' });
const page = await ctx.newPage();
const errors = [];
page.on('console', (m) => { if (['error', 'warning'].includes(m.type())) errors.push(m.type() + ': ' + m.text()); });
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
await page.goto('file://' + resolve('dist/index.html'));
await page.waitForTimeout(500);
await page.click('[data-act="tt-new"]'); await page.waitForTimeout(200);
await page.click('[data-act="ng-go"]'); await page.waitForTimeout(5600);
await page.evaluate(() => { const app = window.__pd; app.settings.tutorial = false; app.turbo = 30; app.setSpeed(3); });
await page.waitForTimeout(5000);
await page.evaluate(() => { window.__pd.turbo = 1; window.__pd.setSpeed(0); });
const before = await page.evaluate(() => ({ t: window.__pd.G.t, money: Math.round(window.__pd.G.money), games: window.__pd.G.games.length }));
console.log('before reload', before);
// Besvara väntande prompter (årsrapporten vid t=48) först; M öppnar inte menyn under en prompt
for (let i = 0; i < 6 && (await page.evaluate(() => window.__pd.promptActive)); i++) {
  if (await page.$('[data-act="yr-ok"]')) await page.click('[data-act="yr-ok"]');
  else await page.evaluate(() => { window.__pd.G.pending.shift(); window.__ui.closeModal(); });
  await page.waitForTimeout(250);
}
await page.keyboard.press('m'); await page.waitForTimeout(400);
await page.screenshot({ path: '.shots-save/menu.png' });
await page.click('[data-act="mn-set"]'); await page.waitForTimeout(400);
await page.screenshot({ path: '.shots-save/settings.png' });
await page.click('[data-act="set-lang"][data-l="en"]'); await page.waitForTimeout(400);
await page.screenshot({ path: '.shots-save/settings-en.png' });
// Språkbytet får inte koppla dokumentlyssnarna igen (då körs varje klick två gånger)
const crt0 = await page.evaluate(() => !!window.__pd.settings.crt);
await page.click('[data-act="set-tog"][data-k="crt"]'); await page.waitForTimeout(200);
const crt1 = await page.evaluate(() => !!window.__pd.settings.crt);
await page.click('[data-act="set-tog"][data-k="crt"]'); await page.waitForTimeout(200);
await page.evaluate(() => window.__ui.close(true));
await page.click('#dock [data-act="dock"][data-id="staff"]'); await page.waitForTimeout(300);
const cur = await page.evaluate(() => window.__ui.cur);
await page.evaluate(() => window.__ui.close(true));
await page.hover('[data-act="menu"]'); await page.waitForTimeout(200);
const tipOn = await page.evaluate(() => document.querySelector('#tip').classList.contains('on'));
console.log('after language switch: set-tog flips', crt1 !== crt0, '| dock opens', cur, '| tooltip shows', tipOn);
if (crt1 === crt0 || cur !== 'staff' || !tipOn) errors.push('fail: clicks after language switch (crt ' + crt0 + '->' + crt1 + ', cur ' + cur + ', tip ' + tipOn + ')');
await page.evaluate(() => { window.__ui.close(true); window.__pd.toTitle(); });
await page.waitForTimeout(800);
await page.screenshot({ path: '.shots-save/title-continue.png' });
await page.reload(); await page.waitForTimeout(800);
const hasCont = await page.$('[data-act="tt-continue"]');
console.log('continue button after reload:', !!hasCont);
await page.click('[data-act="tt-continue"]'); await page.waitForTimeout(1500);
const after = await page.evaluate(() => ({ t: window.__pd.G.t, money: Math.round(window.__pd.G.money), games: window.__pd.G.games.length, lang: document.documentElement.lang }));
console.log('after continue', after);
await page.screenshot({ path: '.shots-save/continued.png' });
console.log(errors.length ? errors.join('\n') : 'no console errors');
await browser.close();
