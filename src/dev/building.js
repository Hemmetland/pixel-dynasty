import { makeLayout, drawShell, eraOf } from '../render/building.js';
import { drawPerson } from '../render/people.js';
const tier = +(new URLSearchParams(location.search).get('tier') || 0);
const L = makeLayout(tier);
const c = document.createElement('canvas');
const W = 520, H = 340;
c.width = W; c.height = H;
const s = Math.min(Math.floor(1280 / W), 3);
c.style.cssText = `width:${W * s}px;height:${H * s}px;image-rendering:pixelated;display:block`;
document.body.style.cssText = 'margin:0;background:#222';
document.body.appendChild(c);
const g = c.getContext('2d');
const grad = g.createLinearGradient(0, 0, 0, H);
grad.addColorStop(0, '#4aa8ff'); grad.addColorStop(1, '#bfe4ff');
g.fillStyle = grad; g.fillRect(0, 0, W, H);
g.fillStyle = '#7a8a9a'; g.fillRect(0, H - 40, W, 40);
g.save();
g.translate(W / 2, H - 40);
const fac = { coffee: { lvl: 2, slot: 0 }, lab: { lvl: 2, slot: 1 }, qa: { lvl: 1, slot: 2 }, training: { lvl: 2, slot: 3 }, gameroom: { lvl: 2, slot: 4 }, marketing: { lvl: 1, slot: 5 }, server: { lvl: 2, slot: 6 } };
const f2 = {};
for (const [k, v] of Object.entries(fac)) if (v.slot < L.slots.length) f2[k] = v;
const layer = document.createElement('canvas');
layer.width = L.W + 40; layer.height = L.H + 40;
const lg = layer.getContext('2d');
lg.translate(layer.width / 2, layer.height - 4);
drawShell(lg, L, { era: eraOf(1980 + tier * 8), name: 'Nordlys Games', awards: 2, games: [{ c1: '#4a90e0', c2: '#2a5090' }, { c1: '#e8504a', c2: '#902a2a' }], fac: f2 });
g.drawImage(layer, -layer.width / 2, -layer.height + 4);
for (const d of L.desks.slice(0, 12)) drawPerson(g, d.x + 6, d.fy, { skin: d.idx % 5, hair: d.idx % 7, hairColor: d.idx % 9, shirt: d.idx % 12, pants: d.idx % 4, acc: d.idx % 5 }, 'sit', d.idx % 2, 1);
g.restore();
